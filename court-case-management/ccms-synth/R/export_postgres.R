# PostgreSQL bundle: machine-format CSV + generated psql load script --------
# COPY requires '.' as decimal mark, so these CSVs differ from the EU-locale ones.

TRUTH_TABLES <- c("truth_parameter", "truth_case", "truth_hearing", "truth_counsel")

write_csv_machine <- function(dt, path) {
  atomic_write(path, function(tmp) {
    data.table::fwrite(dt, tmp, sep = ",", dec = ".", na = "", quote = "auto", scipen = 100L)
  })
}

#' Write CSVs and a load.sql that creates the schema and loads all tables in one transaction.
write_postgres_bundle <- function(tables, out_dir, pg_sql_dir) {
  dir <- ensure_dir(file.path(out_dir, "postgres"))
  csv_dir <- ensure_dir(file.path(dir, "csv"))
  ddl <- sort(list.files(pg_sql_dir, pattern = "^[0-9]{3}_.*\\.sql$", full.names = TRUE))
  if (length(ddl) == 0) ccms_abort(sprintf("No PostgreSQL DDL found in '%s'", pg_sql_dir), "ccms_io_error")
  ddl_dir <- ensure_dir(file.path(dir, "ddl"))
  if (!all(file.copy(ddl, ddl_dir, overwrite = TRUE))) ccms_abort("Copying PostgreSQL DDL failed", "ccms_io_error")
  # Paths are relative: run psql from this directory (psql copy resolves against the client cwd).
  lines <- c("-- Generated by ccms-synth. Usage: cd <this directory> && psql -d <database> -f load.sql",
             "\\set ON_ERROR_STOP on", "BEGIN;",
             "DROP SCHEMA IF EXISTS ccms_truth CASCADE;", "DROP SCHEMA IF EXISTS ccms CASCADE;",
             sprintf("\\i ddl/%s", basename(ddl)))
  for (tb in TABLE_ORDER) {
    write_csv_machine(tables[[tb]], file.path(csv_dir, paste0(tb, ".csv")))
    schema <- if (tb %in% TRUTH_TABLES) "ccms_truth" else "ccms"
    cols <- paste(names(tables[[tb]]), collapse = ", ")
    lines <- c(lines, sprintf("\\copy %s.%s (%s) FROM 'csv/%s.csv' WITH (FORMAT csv, HEADER true)",
                              schema, tb, cols, tb))
  }
  lines <- c(lines, "COMMIT;", "ANALYZE;")
  path <- file.path(dir, "load.sql")
  atomic_write(path, function(tmp) writeLines(lines, tmp, useBytes = TRUE))
  log_info("PostgreSQL bundle written: ", path)
  invisible(path)
}
